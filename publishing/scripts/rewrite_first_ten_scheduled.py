def _sync_local_logs(base: Path, updates: dict[str, dict[str, str]]) -> None:
    log_path = base / "data" / "published-log.json"
    state_path = base / "data" / "publishing-state.json"

    log = json.loads(log_path.read_text(encoding="utf-8"))
    for item in log:
        update = updates.get(item["file"])
        if update:
            item["caption"] = update["caption"]
            item["zernio_post_id"] = update["post_id"]
    log_path.write_text(json.dumps(log, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    state = json.loads(state_path.read_text(encoding="utf-8"))
    for file_name, update in updates.items():
        if file_name in state:
            state[file_name]["zernio_post_id"] = update["post_id"]
            state[file_name]["current_caption"] = update["caption"]
    state_path.write_text(json.dumps(state, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    cfg = load_config()
    sdk = ZernioClient(cfg)._sdk()

    resp = sdk.posts.list(status="scheduled", profile_id=cfg.zernio_profile_id, limit=50)
    posts = getattr(resp, "posts", []) or []

    post_map: dict[str, str] = {}
    for post in posts:
        media_items = getattr(post, "mediaItems", None) or []
        first_media = media_items[0] if media_items else None
        media_url = str(_item_get(first_media, "url") or "")
        file_name = Path(media_url).name
        for target_file in CAPTIONS:
            stem = Path(target_file).stem
            if media_url and stem in file_name:
                post_id = str(_item_get(post, "field_id") or _item_get(post, "id") or "")
                if post_id:
                    post_map[target_file] = post_id
                break

    missing = sorted(set(CAPTIONS) - set(post_map))
    if missing:
        raise RuntimeError(f"Could not map scheduled posts for: {missing}")

    updates: dict[str, dict[str, str]] = {}
    for file_name, caption in CAPTIONS.items():
        post_id = post_map[file_name]
        sdk.posts.update(post_id, content=caption)
        updates[file_name] = {"post_id": post_id, "caption": caption}

    _sync_local_logs(ROOT, updates)
    print(json.dumps({"updated_files": list(CAPTIONS.keys())}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
